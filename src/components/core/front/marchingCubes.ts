export function generateMeshFromSDF(
  boundsMin: [number, number, number],
  boundsMax: [number, number, number],
  cellSize: number,
  sdf: (x: number, y: number, z: number) => number,
  colorFn: (x: number, y: number, z: number) => [number, number, number],
  depthFn?: (x: number, y: number, z: number) => number
): BufferGeometry | null {
  const nx = Math.ceil((boundsMax[0] - boundsMin[0]) / cellSize);
  const ny = Math.ceil((boundsMax[1] - boundsMin[1]) / cellSize);
  const nz = Math.ceil((boundsMax[2] - boundsMin[2]) / cellSize);
  if (nx < 1 || ny < 1 || nz < 1) return null;

  const gx = nx + 1;
  const gy = ny + 1;

  const field = new Float32Array(gx * gy * (nz + 1));
  for (let k = 0; k <= nz; k++) {
    const wz = boundsMin[2] + k * cellSize;
    for (let j = 0; j <= ny; j++) {
      const wy = boundsMin[1] + j * cellSize;
      for (let i = 0; i <= nx; i++) {
        field[i + gx * (j + gy * k)] = sdf(boundsMin[0] + i * cellSize, wy, wz);
      }
    }
  }

  const positions: number[] = [];
  const colors: number[] = [];
  const indices: number[] = [];
  const depths: number[] = [];

  for (let k = 0; k < nz; k++) {
    for (let j = 0; j < ny; j++) {
      for (let i = 0; i < nx; i++) {
        const idx00 = i + gx * (j + gy * k);
        const f0 = field[idx00];
        const f1 = field[idx00 + 1];
        const f2 = field[idx00 + 1 + gx];
        const f3 = field[idx00 + gx];
        const f4 = field[idx00 + gx * gy];
        const f5 = field[idx00 + 1 + gx * gy];
        const f6 = field[idx00 + 1 + gx + gx * gy];
        const f7 = field[idx00 + gx + gx * gy];

        let ci = 0;
        if (f0 < 0) ci |= 1;
        if (f1 < 0) ci |= 2;
        if (f2 < 0) ci |= 4;
        if (f3 < 0) ci |= 8;
        if (f4 < 0) ci |= 16;
        if (f5 < 0) ci |= 32;
        if (f6 < 0) ci |= 64;
        if (f7 < 0) ci |= 128;

        const bits = EDGE_TABLE[ci];
        if (bits === 0) continue;

        const x0 = boundsMin[0] + i * cellSize;
        const y0 = boundsMin[1] + j * cellSize;
        const z0 = boundsMin[2] + k * cellSize;
        const cs = cellSize;

        const ev = new Float32Array(36);

        if (bits & 1)    { const t = f0 / (f0 - f1); ev[0]  = x0 + t * cs; ev[1]  = y0;          ev[2]  = z0; }
        if (bits & 2)    { const t = f1 / (f1 - f2); ev[3]  = x0 + cs;      ev[4]  = y0 + t * cs; ev[5]  = z0; }
        if (bits & 4)    { const t = f3 / (f3 - f2); ev[6]  = x0 + t * cs; ev[7]  = y0 + cs;      ev[8]  = z0; }
        if (bits & 8)    { const t = f0 / (f0 - f3); ev[9]  = x0;           ev[10] = y0 + t * cs; ev[11] = z0; }
        if (bits & 16)   { const t = f4 / (f4 - f5); ev[12] = x0 + t * cs; ev[13] = y0;          ev[14] = z0 + cs; }
        if (bits & 32)   { const t = f5 / (f5 - f6); ev[15] = x0 + cs;      ev[16] = y0 + t * cs; ev[17] = z0 + cs; }
        if (bits & 64)   { const t = f7 / (f7 - f6); ev[18] = x0 + t * cs; ev[19] = y0 + cs;      ev[20] = z0 + cs; }
        if (bits & 128)  { const t = f4 / (f4 - f7); ev[21] = x0;           ev[22] = y0 + t * cs; ev[23] = z0 + cs; }
        if (bits & 256)  { const t = f0 / (f0 - f4); ev[24] = x0;           ev[25] = y0;          ev[26] = z0 + t * cs; }
        if (bits & 512)  { const t = f1 / (f1 - f5); ev[27] = x0 + cs;      ev[28] = y0;          ev[29] = z0 + t * cs; }
        if (bits & 1024) { const t = f2 / (f2 - f6); ev[30] = x0 + cs;      ev[31] = y0 + cs;      ev[32] = z0 + t * cs; }
        if (bits & 2048) { const t = f3 / (f3 - f7); ev[33] = x0;           ev[34] = y0 + cs;      ev[35] = z0 + t * cs; }

        const tb = ci << 4;
        for (let n = 0; TRI_TABLE[tb + n] !== -1; n += 3) {
          const e0 = TRI_TABLE[tb + n] * 3;
          const e1 = TRI_TABLE[tb + n + 1] * 3;
          const e2 = TRI_TABLE[tb + n + 2] * 3;

          const vi = positions.length / 3;
          positions.push(ev[e0], ev[e0 + 1], ev[e0 + 2]);
          positions.push(ev[e1], ev[e1 + 1], ev[e1 + 2]);
          positions.push(ev[e2], ev[e2 + 1], ev[e2 + 2]);

          const c0 = colorFn(ev[e0], ev[e0 + 1], ev[e0 + 2]);
          const c1 = colorFn(ev[e1], ev[e1 + 1], ev[e1 + 2]);
          const c2 = colorFn(ev[e2], ev[e2 + 1], ev[e2 + 2]);
          colors.push(c0[0], c0[1], c0[2]);
          colors.push(c1[0], c1[1], c1[2]);
          colors.push(c2[0], c2[1], c2[2]);

          if (depthFn) {
            depths.push(depthFn(ev[e0], ev[e0 + 1], ev[e0 + 2]));
            depths.push(depthFn(ev[e1], ev[e1 + 1], ev[e1 + 2]));
            depths.push(depthFn(ev[e2], ev[e2 + 1], ev[e2 + 2]));
          }

          indices.push(vi, vi + 1, vi + 2);
        }
      }
    }
  }

  if (positions.length < 9) return null;

  const tolerance = cellSize * 0.01;
  const vertexMap = new Map<string, number>();
  const mergedPositions: number[] = [];
  const mergedColors: number[] = [];
  const mergedDepths: number[] = [];
  const mergedIndices: number[] = [];
  const colorAccum: number[][] = [];
  const depthAccum: number[][] = [];
  
  for (let i = 0; i < positions.length; i += 3) {
    const x = positions[i];
    const y = positions[i + 1];
    const z = positions[i + 2];
    
    const kx = Math.round(x / tolerance);
    const ky = Math.round(y / tolerance);
    const kz = Math.round(z / tolerance);
    const key = `${kx},${ky},${kz}`;
    
    let vertIndex = vertexMap.get(key);
    if (vertIndex === undefined) {
      vertIndex = mergedPositions.length / 3;
      vertexMap.set(key, vertIndex);
      mergedPositions.push(x, y, z);
      const ci = i;
      colorAccum.push([colors[ci], colors[ci + 1], colors[ci + 2], 1]);
      if (depths.length > 0) {
        depthAccum.push([depths[i / 3], 1]);
      }
    } else {
      const ci = i;
      colorAccum[vertIndex][0] += colors[ci];
      colorAccum[vertIndex][1] += colors[ci + 1];
      colorAccum[vertIndex][2] += colors[ci + 2];
      colorAccum[vertIndex][3] += 1;
      if (depths.length > 0) {
        depthAccum[vertIndex][0] += depths[i / 3];
        depthAccum[vertIndex][1] += 1;
      }
    }
    
    mergedIndices.push(vertIndex);
  }
  
  for (let i = 0; i < colorAccum.length; i++) {
    const count = colorAccum[i][3];
    mergedColors.push(
      colorAccum[i][0] / count,
      colorAccum[i][1] / count,
      colorAccum[i][2] / count
    );
    if (depthAccum.length > 0) {
      mergedDepths.push(depthAccum[i][0] / depthAccum[i][1]);
    }
  }

  const geo = new BufferGeometry();
  geo.setAttribute('position', new Float32BufferAttribute(mergedPositions, 3));
  geo.setAttribute('color', new Float32BufferAttribute(mergedColors, 3));
  if (mergedDepths.length > 0) {
    geo.setAttribute('interiorDepth', new Float32BufferAttribute(mergedDepths, 1));
  }
  geo.setIndex(mergedIndices);
  geo.computeVertexNormals();
  return geo;
}
